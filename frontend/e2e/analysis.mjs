// New features: common returns, right-click transfer functions, pole design, robustness. Usage: node e2e/analysis.mjs [port]
import { chromium } from 'playwright-core';
import { mkdirSync } from 'node:fs';
const port = process.argv[2] ?? '8001', out = 'e2e/shots'; mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1500, height: 980 } });
const errors = []; page.on('pageerror', e => errors.push(String(e))); page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
const checks = []; const check = (name, ok) => { checks.push({ name, ok: !!ok }); console.log(ok ? 'PASS' : 'FAIL', name); };
await page.goto(`http://127.0.0.1:${port}/`); await page.locator('.action-bar').getByRole('button', { name: 'Run simulation' }).waitFor();
await page.getByRole('button', { name: /^Model$/ }).click(); await page.waitForTimeout(800);
const open = async name => { await page.getByRole('button', { name: `Expand ${name}` }).dispatchEvent('click'); await page.waitForTimeout(900); };
await open('Housing Market System'); await open('CPB housing model');
await page.locator('.map-canvas').screenshot({ path: `${out}/20_cpb_even.png` });
check('no dots at rail bends', await page.locator('.rail > circle').count() === 0);
// right-click: imputed rent as input, measured price as output
await page.locator('.rail').filter({ hasText: 'Imputed rent' }).locator('.rail-hit').first().dispatchEvent('contextmenu', { clientX: 700, clientY: 400, button: 2 });
check('right-click opens the menu', await page.getByRole('menu').isVisible());
await page.getByRole('menuitem', { name: 'Use as input' }).click();
await page.locator('.signal').filter({ hasText: 'House price' }).locator('.rail-hit').dispatchEvent('contextmenu', { clientX: 900, clientY: 300, button: 2 });
await page.getByRole('menuitem', { name: 'Use as output' }).click();
await page.getByText('A permanent change of 1').or(page.getByText('keeps drifting')).first().waitFor({ timeout: 15000 });
check('transfer function shows gain, phase and step', await page.locator('.inspector [role=img]').count() >= 3 && await page.locator('.pole-table tbody tr').count() > 0);
await page.screenshot({ path: `${out}/21_tf_map.png` });
await open('Investors'); await page.waitForTimeout(400);
check('investors draws common returns with junction dots', await page.locator('.circuit .return-dot').count() >= 7);
await page.getByRole('button', { name: 'Collapse CPB housing model' }).dispatchEvent('click'); await page.waitForTimeout(300);
await open('CPB housing model'); await open('Investors');
await page.locator('.react-flow__node').filter({ hasText: 'Investors' }).last().screenshot({ path: `${out}/22_investors.png` });
await open('Households'); await page.locator('.react-flow__node[data-id="households"]').screenshot({ path: `${out}/23_households.png` });
await open('Firms'); await page.locator('.react-flow__node[data-id="firms"]').screenshot({ path: `${out}/24_firms.png` });
await open('Financial sector'); await open('Bank'); await page.locator('.react-flow__node[data-id="bank"]').screenshot({ path: `${out}/25_bank.png` });
// pole design
await page.getByRole('button', { name: /Pole design/ }).click();
await page.locator('.verdict').waitFor({ timeout: 30000 });
check('pole plot draws the closed-loop poles', await page.locator('.pp-pole').count() >= 10);
const before = await page.locator('.pp-spec-label').first().textContent();
const h = await page.getByRole('slider', { name: 'Settling-time line' }).boundingBox();
await page.mouse.move(h.x + h.width / 2, h.y + h.height / 2); await page.mouse.down(); await page.mouse.move(h.x - 120, h.y + 40, { steps: 6 }); await page.mouse.up(); await page.waitForTimeout(500);
const after = await page.locator('.pp-spec-label').first().textContent();
check(`dragging the line changes the spec (${before} → ${after})`, before !== after);
await page.getByRole('button', { name: 'Ziegler–Nichols (thesis gains)' }).click(); await page.waitForTimeout(800);
check('ZN preset leaves poles outside the lines', /outside your lines/.test(await page.locator('.verdict').innerText()));
await page.screenshot({ path: `${out}/26_poles_zn.png`, fullPage: true });
await page.getByRole('button', { name: 'H∞ PID' }).click(); await page.waitForTimeout(400);
await page.getByLabel('Shocks gone within').fill('5'); await page.getByLabel('Largest overshoot').fill('30');
await page.getByRole('button', { name: /Find gains for my lines/ }).click();
await page.getByText(/Found gains|No gains meet/).waitFor({ timeout: 30000 }); await page.waitForTimeout(800);
check('auto-tune returns gains', true);
await page.screenshot({ path: `${out}/27_poles_tuned.png`, fullPage: true });
// robustness
await page.getByRole('button', { name: /Robustness/ }).click();
await page.locator('.robust-card').first().waitFor({ timeout: 30000 }); await page.waitForTimeout(1500);
check('three robustness panels', await page.locator('.robust-card').count() === 3);
await page.getByRole('button', { name: /Draw 100 markets/ }).click();
await page.getByText(/% stable \(/).first().waitFor({ timeout: 60000 }); await page.waitForTimeout(1200);
check('Monte Carlo reports stable fractions', await page.locator('.kpis.three .kpi').count() === 3);
await page.screenshot({ path: `${out}/28_robust.png`, fullPage: true });
check('no browser errors', errors.length === 0); if (errors.length) console.log(errors);
await browser.close();
const failed = checks.filter(c => !c.ok).length; console.log(`${checks.length - failed}/${checks.length} checks passed`); process.exit(failed ? 1 : 0);
